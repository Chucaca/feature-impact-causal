"""Command line entry point: ``python -m feature_impact.cli run``."""
from __future__ import annotations

import argparse
import time
from pathlib import Path

import pandas as pd

from . import plots
from .pipeline import evaluate, feature_table, run_monthly
from .psm import estimate_att
from .summary import summarize, to_markdown
from .synthetic import CAT_CONFOUNDERS, FEATURE_NAMES, NUM_CONFOUNDERS, generate, treatment_col

FEATURE_COLS = [
    "feature", "quadrant", "harmful", "adoption_rate", "naive_diff", "psm_att", "psm_ci_low", "psm_ci_high",
    "psm_lift", "months_significant", "confirmed", "direction", "trend", "trend_slope", "naive_months_significant",
    "naive_confirmed", "max_abs_smd_after", "aha_effect", "aha_psm_att", "aha_months_significant", "aha_confirmed",
    "aha_trend", "aha_interpretable_months", "true_att", "aha_true_att",
]


def _md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in df.itertuples(index=False):
        cells = []
        for v in r:
            if isinstance(v, float):
                cells.append("-" if pd.isna(v) else f"{v:.2f}")
            else:
                cells.append(str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def evaluation_markdown(ev: pd.DataFrame) -> str:
    e = ev.copy()
    e["ci_coverage"] = e["ci_coverage"].map(lambda v: "-" if pd.isna(v) else f"{v:.0%}")
    for c in ("false_confirmed", "missed", "wrong_sign"):
        e[c] = e[c].map(lambda v: "-" if pd.isna(v) else str(int(v)))
    e = e.rename(
        columns={
            "outcome": "Outcome", "method": "Method", "n_estimates": "N", "bias_pp": "Bias (pp)",
            "mae_pp": "MAE (pp)", "rmse_pp": "RMSE (pp)", "ci_coverage": "95% CI coverage",
            "false_confirmed": "Null features confirmed", "missed": "Real effects missed",
            "wrong_sign": "Confirmed with wrong sign",
        }
    )
    return _md_table(e)


def cmd_run(args: argparse.Namespace) -> None:
    root = Path(args.out)
    reports, img = root / "reports", root / "docs" / "img"
    reports.mkdir(parents=True, exist_ok=True)
    img.mkdir(parents=True, exist_ok=True)
    t0 = time.time()

    print(f"Generating synthetic data: {args.months} snapshots x {args.n_per_month:,} merchants (seed={args.seed})")
    data = generate(n_per_month=args.n_per_month, n_months=args.months, seed=args.seed)

    print("Running naive / PSM / stratified estimators per snapshot ...")
    monthly = run_monthly(data.df, FEATURE_NAMES, truth=data.truth, n_boot=args.n_boot, seed=args.seed, progress=True)
    table = feature_table(monthly, min_sig_months=args.min_sig_months)
    ev = evaluate(monthly, min_sig_months=args.min_sig_months)

    monthly.to_csv(reports / "monthly_estimates.csv", index=False, float_format="%.5f")
    table[FEATURE_COLS].sort_values("psm_att", ascending=False).to_csv(
        reports / "feature_impact.csv", index=False, float_format="%.5f"
    )
    ev.to_csv(reports / "evaluation.csv", index=False, float_format="%.4f")

    summary, source = summarize(table, provider=args.llm)
    md = [
        "# Feature impact summary (SYNTHETIC DATA)",
        "",
        f"Generated by `python -m feature_impact.cli run` - summary source: **{source}**. "
        f"{args.months} monthly snapshots x {args.n_per_month:,} merchants; all numbers come from a simulator.",
        "",
        to_markdown(summary),
        "## Evaluation against the simulator's ground truth",
        "",
        "Each row pools all feature x snapshot estimates "
        f"({len(FEATURE_NAMES)} features x {args.months} snapshots). Bias/MAE/RMSE in percentage points.",
        "",
        evaluation_markdown(ev),
        "",
    ]
    (reports / "summary.md").write_text("\n".join(md), encoding="utf-8")

    print("Drawing charts ...")
    plots.hero_chart(table, img / "naive_vs_psm_vs_truth.png")
    first = data.df[data.df["snapshot"] == 1]
    res = estimate_att(first, treatment_col(args.love_feature), "renewed", CAT_CONFOUNDERS, NUM_CONFOUNDERS,
                       n_boot=50, seed=args.seed)
    plots.love_plot(res.balance, args.love_feature, img / "love_plot.png")
    plots.quadrant_chart(table, img / "adoption_impact_quadrants.png")

    print("\nEvaluation (pp = percentage points):")
    print(ev.round(3).to_string(index=False))
    print("\nQuadrants:")
    print(table[["feature", "quadrant", "adoption_rate", "psm_att", "months_significant", "trend"]]
          .sort_values(["quadrant", "psm_att"]).round(3).to_string(index=False))
    print(f"\nDone in {time.time() - t0:.0f}s -> {reports}, {img}")


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(prog="feature_impact", description="Causal feature impact on synthetic POS SaaS data")
    sub = p.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("run", help="generate data, estimate, evaluate, write reports and charts")
    r.add_argument("--n-per-month", type=int, default=10_000)
    r.add_argument("--months", type=int, default=6)
    r.add_argument("--seed", type=int, default=42)
    r.add_argument("--n-boot", type=int, default=500)
    r.add_argument("--min-sig-months", type=int, default=4)
    r.add_argument("--love-feature", default="multi_branch_transfer")
    r.add_argument("--llm", default=None, help="gemini | openai | none (default: $FEATURE_IMPACT_LLM or none)")
    r.add_argument("--out", default=".", help="repo root to write reports/ and docs/img/ into")
    r.set_defaults(func=cmd_run)
    args = p.parse_args(argv)
    args.func(args)


if __name__ == "__main__":
    main()
